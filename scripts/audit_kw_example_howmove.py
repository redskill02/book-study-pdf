def norm(s):
    return re.sub(r"[\s,·\.]", "", s)


def norm_html(s):
    s = re.sub(r"<[^>]+>", "", s)
    s = re.sub(r"&[a-zA-Z]+;", "", s)
    s = re.sub(r"&#\d+;", "", s)
    return norm(s)


