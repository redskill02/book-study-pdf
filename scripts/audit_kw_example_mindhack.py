    if norm(label) not in norm(note) and not any(norm(c) in norm(note) for c in cands):
        continue                       # 노트에서 안 썼다 → 검사 대상 아님
    used.append(label)
    if not any(norm(c) in SRC for c in cands):
        missing.append((label, cands))

